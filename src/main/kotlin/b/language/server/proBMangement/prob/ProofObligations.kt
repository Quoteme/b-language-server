/**
 * A hypothesis of a proof obligation: [origin] is the label of the axiom, invariant, guard,
 * action or witness it comes from. As in Rodin, the hypotheses local to an event, and those
 * about the identifiers of the goal, are selected; the others are only searched.
 */
class Hypothesis(val predicate: Predicate, val origin: String?, val selected: Boolean)

/**
 * A proof obligation as generated by Rodin's proof obligation generator
 * (Rodin Handbook 3.2.5 to 3.2.7): the goal must follow from the hypotheses.
 */
class ProofObligation(
    val name: String,
    val file: File,
    val line: Int,
    val pos: Int,
    val length: Int,
    /** The types of the identifiers, including after-values (x') and parameters. */
    val env: ITypeEnvironment,
    val hypotheses: List<Hypothesis>,
    val goal: Predicate,
) {
    /** A counterexample to this predicate disproves the obligation. */
    val negation: String get() = ProBText.negation(env, hypotheses.map { it.predicate }, goal)

    var status = Status.UNDISCHARGED
    var detail = ""

    enum class Status {
        /** ProB found no counterexample. */
        DISCHARGED,
        /** Proved interactively; the proof is in the component's .bpr file. */
        PROVED,
        /** The interactive proof has reviewed steps. */
        REVIEWED,
        DISPROVED,
        UNDISCHARGED,
        /** The saved proof no longer applies to the obligation. */
        BROKEN,
    }

    val closed get() = status == Status.DISCHARGED || status == Status.PROVED || status == Status.REVIEWED

    /**
     * Takes the status from an interactive proof: a complete proof proves the obligation. An
     * incomplete one leaves ProB's verdict, if there is one.
     */
    fun updateStatus(tree: ProofTree) {
        status = when {
            tree.complete -> if (tree.confidence <= Confidence.REVIEWED_MAX) Status.REVIEWED else Status.PROVED
            status == Status.DISCHARGED || status == Status.DISPROVED -> status
            tree.root.nodes().any { it.broken != null } -> Status.BROKEN
            else -> Status.UNDISCHARGED
        }
    }

    /** How the obligation shows among the problems of its file, if at all. */
    fun diagnostic(): Diagnostic? = when (status) {
        Status.DISCHARGED, Status.PROVED, Status.REVIEWED -> null
        Status.DISPROVED ->
            diagnostic(file, line, pos, length, if (detail.isEmpty()) "$name does not hold" else "$name does not hold, e.g. for $detail", DiagnosticSeverity.Warning)
        Status.UNDISCHARGED ->
            diagnostic(file, line, pos, length, "$name is not discharged by ProB: $detail", DiagnosticSeverity.Hint)
        Status.BROKEN ->
            diagnostic(file, line, pos, length, "$name: its saved proof no longer applies; reprove it with :ProbProve", DiagnosticSeverity.Hint)
    }
}

/** ProB cannot read primed identifiers, so x' becomes x_prime. */
const val PRIME_SUFFIX = "_prime"

/** Event-B predicates as ProB reads them. */
object ProBText {
    private val PRIMED = Regex("([A-Za-z_][A-Za-z0-9_]*)'")

    /** [text] with x' written as x_prime. */
    fun unprimed(text: String) = text.replace(PRIMED) { it.groupValues[1] + PRIME_SUFFIX }

    /**
     * The conjunction of the hypotheses and the negated goal, typed: ProB cannot always infer
     * the types from the predicates alone, as in x' = ∅, so every identifier mentioned gets a
     * typing predicate, as in Rodin's type environment.
     */
    fun negation(env: ITypeEnvironment, hypotheses: List<Predicate>, goal: Predicate): String {
        val conjuncts = hypotheses.map { unprimed(it.toString()) } + "¬(${unprimed(goal.toString())})"
        val text = conjuncts.joinToString(" ")
        val typing = mutableListOf<String>()
        val iterator = env.iterator
        while (iterator.hasNext()) {
            iterator.advance()
            if (iterator.isGivenSet) continue
            val name = unprimed(iterator.name)
            if (Regex("(?<![\\w'])${Regex.escape(name)}(?![\\w'])").containsMatchIn(text)) {
                typing += "$name ∈ ${iterator.type.toExpression()}"
            }
        }
        return (typing + conjuncts).joinToString(" ∧ ") { "($it)" }
    }
}

/** Generates the proof obligations of a checked context or machine. */
class ProofObligationGenerator {

    private val obligations = mutableListOf<ProofObligation>()
    private val factory = FormulaFactory.getDefault()

    /** The identifiers in scope, with their after-values and the parameters of the current event. */
    private var env: ITypeEnvironmentBuilder = factory.makeTypeEnvironment()

    fun generate(info: Any?): List<ProofObligation> {
        when (info) {
            is ContextInfo -> context(info)
            is MachineInfo -> machine(info)
        }
        return obligations
    }

    private fun po(name: String, file: File, token: Token, hypotheses: List<Hypothesis>, goal: Predicate) {
        // Hypotheses about the goal's identifiers, or their after-values, are selected, like
        // Rodin's selection hints.
        fun names(p: Predicate) = p.freeIdentifiers.map { it.name.removeSuffix("'") }.toSet()
        val identifiers = names(goal)
        val selected = hypotheses.distinctBy { it.predicate }.map { h ->
            if (h.selected || names(h.predicate).none { it in identifiers }) h
            else Hypothesis(h.predicate, h.origin, true)
        }
        obligations += ProofObligation(name, file, token.line, token.pos, token.text.length, env.makeSnapshot(), selected, goal)
    }

    /** [env] with the after-value of every variable. */
    private fun withPrimes(base: ITypeEnvironment, extra: Map<String, Type> = emptyMap()): ITypeEnvironmentBuilder {
        val result = base.makeBuilder()
        val iterator = base.iterator
        while (iterator.hasNext()) {
            iterator.advance()
            if (!iterator.isGivenSet && !iterator.name.endsWith("'") && !result.contains(iterator.name + "'")) {
                result.addName(iterator.name + "'", iterator.type)
            }
        }
        extra.forEach { (name, type) -> if (!result.contains(name)) result.addName(name, type) }
        return result
    }

    /** Parses and type-checks a goal built from text in Rodin's notation. */
    private fun pred(text: String): Predicate {
        val result = factory.parsePredicate(text, null)
        check(!result.hasProblem()) { "cannot parse generated predicate $text: ${result.problems}" }
        val predicate = result.parsedPredicate
        val typeCheck = predicate.typeCheck(env)
        check(!typeCheck.hasProblem()) { "cannot type generated predicate $text: ${typeCheck.problems}" }
        return predicate
    }

    private fun local(predicate: Predicate, origin: String?) = Hypothesis(predicate, origin, true)
    private fun global(predicate: Predicate, origin: String?) = Hypothesis(predicate, origin, false)

    private fun context(info: ContextInfo) {
        val file = info.component.file
        env = withPrimes(info.env)
        val hypotheses = info.extended.flatMap { it.closure() }.distinct().flatMap { c -> c.axioms.map { global(it.formula, it.label) } }.toMutableList()
        for (axiom in info.axioms) {
            wd(axiom.formula)?.let { po("${axiom.label}/WD", file, axiom.token, hypotheses, it) }
            if (axiom.theorem) po("${axiom.label}/THM", file, axiom.token, hypotheses, axiom.formula)
            hypotheses += global(axiom.formula, axiom.label)
        }
    }

    private fun machine(info: MachineInfo) {
        val file = info.component.file
        env = withPrimes(info.env)
        val axioms = info.contexts.flatMap { c -> c.axioms.map { global(it.formula, it.label) } }
        val abstractInvariants = info.abstractInvariants.map { global(it, null) }
        val invariants = info.invariants.map { global(it.formula, it.label) }
        val base = axioms + abstractInvariants + invariants

        val before = (axioms + abstractInvariants).toMutableList()
        for (invariant in info.invariants) {
            wd(invariant.formula)?.let { po("${invariant.label}/WD", file, invariant.token, before, it) }
            if (invariant.theorem) po("${invariant.label}/THM", file, invariant.token, before, invariant.formula)
            before += global(invariant.formula, invariant.label)
        }

        info.variant?.let { variant ->
            wd(variant.formula)?.let { po("VWD", file, variant.token, base, it) }
            if (variant.formula.type !is IntegerType && info.events.values.any { it.convergence != Convergence.ORDINARY }) {
                po("FIN", file, variant.token, base, pred("finite(${variant.formula})"))
            }
        }

        for (event in info.events.values) event(info, event, axioms, base)
    }

    private fun event(info: MachineInfo, event: EventInfo, axioms: List<Hypothesis>, base: List<Hypothesis>) {
        val file = info.component.file
        env = withPrimes(info.env, event.parameters + event.refines.flatMap { it.parameters.entries }.associate { it.key to it.value })
        val prefix = event.name
        val state = if (event.isInitialisation) axioms else base

        val guards = mutableListOf<Hypothesis>()
        for (guard in event.guards) {
            wd(guard.formula)?.let { po("$prefix/${guard.label}/WD", file, guard.token, state + guards, it) }
            if (guard.theorem) po("$prefix/${guard.label}/THM", file, guard.token, state + guards, guard.formula)
            guards += local(guard.formula, guard.label)
        }

        val enabled = state + guards
        val actions = event.actions.map { local(it.formula.baPredicate, it.label) }
        for (action in event.actions) {
            wd(action.formula)?.let { po("$prefix/${action.label}/WD", file, action.token, enabled, it) }
            val fis = action.formula.fisPredicate
            if (fis.tag != Formula.BTRUE) po("$prefix/${action.label}/FIS", file, action.token, enabled, fis)
        }

        val abstract = info.abstract
        val abstractVariables = abstract?.variables.orEmpty().toSet()
        val disappearing = abstractVariables - info.variables.toSet()
        val parameterWitnesses = event.witnesses.filter { !it.label.endsWith("'") }.map { local(it.formula, it.label) }
        val witnesses = event.witnesses.map { local(it.formula, it.label) }

        // Abstract after-values that the concrete actions do not determine come from the abstract actions.
        val abstractActions = event.refines.firstOrNull()?.actions.orEmpty()
        val abstractEffects = abstractActions
            .filter { a -> a.formula.tag == Formula.BECOMES_EQUAL_TO && a.formula.assignedIdentifiers.all { it.name in disappearing } }
            .map { local(it.formula.baPredicate, it.label) }
        val after = enabled + witnesses + actions + abstractEffects

        // Variables the event may change, concrete or disappearing abstract ones.
        val changed = event.assigned + abstractActions.flatMap { a -> a.formula.assignedIdentifiers.map { it.name } }.filter { it in disappearing }
        for (invariant in info.invariants.filter { !it.theorem }) {
            val mentioned = invariant.formula.freeIdentifiers.map { it.name }
            if (event.isInitialisation || mentioned.any { it in changed }) {
                val goal = primed(invariant.formula, if (event.isInitialisation) info.allVariables else changed)
                po("$prefix/${invariant.label}/INV", file, event.token, after, goal)
            }
        }

        if (abstract != null && event.refines.isNotEmpty() && !event.extended) {
            if (event.refines.size == 1) {
                val concrete = event.guards.map { it.formula.toString() }.toSet()
                for (guard in event.refines.first().guards.filter { !it.theorem && it.formula.toString() !in concrete }) {
                    po("$prefix/${guard.label}/GRD", file, event.token, enabled + parameterWitnesses, guard.formula)
                }
            } else {
                val alternatives = event.refines.joinToString(" ∨ ") { e ->
                    "(" + e.guards.filter { !it.theorem }.map { it.formula.toString() }.ifEmpty { listOf("⊤") }.joinToString(" ∧ ") { "($it)" } + ")"
                }
                po("$prefix/MRG", file, event.token, after, pred(alternatives))
            }
            val concrete = event.actions.map { it.formula.toString() }.toSet()
            for (action in abstractActions.filter { it.formula.toString() !in concrete }) {
                if (action.formula.assignedIdentifiers.any { it.name in info.variables }) {
                    po("$prefix/${action.label}/SIM", file, event.token, after, action.formula.baPredicate)
                }
            }
        }

        // Common variables keep their value unless the abstract event changes them too.
        if (abstract != null && !event.isInitialisation) {
            val abstractlyAssigned = abstractActions.flatMap { a -> a.formula.assignedIdentifiers.map { it.name } }.toSet()
            for (action in event.actions) {
                for (variable in action.formula.assignedIdentifiers.map { it.name }.filter { it in abstractVariables && it !in abstractlyAssigned }) {
                    po("$prefix/$variable/EQL", file, action.token, enabled + local(action.formula.baPredicate, action.label), pred("$variable' = $variable"))
                }
            }
        }

        for (witness in event.witnesses) {
            val hypotheses = if (witness.label.endsWith("'")) enabled + actions else enabled
            wd(witness.formula)?.let { po("$prefix/${witness.label}/WWD", file, witness.token, state + actions, it) }
            po("$prefix/${witness.label}/WFIS", file, witness.token, hypotheses, pred("∃${witness.label}·(${witness.formula})"))
        }

        val variant = info.variant
        if (variant != null && event.convergence != Convergence.ORDINARY) {
            val now = variant.formula.toString()
            val next = primed(variant.formula, event.assigned).toString()
            val strict = event.convergence == Convergence.CONVERGENT
            if (variant.formula.type is IntegerType) {
                po("$prefix/NAT", file, event.token, enabled, pred("$now ∈ ℕ"))
                po("$prefix/VAR", file, event.token, enabled + actions, pred(if (strict) "$next < $now" else "$next ≤ $now"))
            } else {
                po("$prefix/VAR", file, event.token, enabled + actions, pred(if (strict) "$next ⊂ $now" else "$next ⊆ $now"))
            }
        }
    }

    /** The well-definedness condition of [formula], or null if it is trivial. */
    private fun wd(formula: Formula<*>): Predicate? {
        val wd = formula.wdPredicate
        return if (wd.tag == Formula.BTRUE) null else wd
    }

    /** [formula] with the after-values of [variables]. */
    private fun <T : Formula<T>> primed(formula: T, variables: Collection<String>): T {
        val substitution = formula.freeIdentifiers.filter { it.name in variables && !it.isPrimed }.associateWith { it.withPrime() as Expression }
        return if (substitution.isEmpty()) formula else formula.substituteFreeIdents(substitution)
    }
}
